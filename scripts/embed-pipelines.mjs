// embed-pipelines.mjs — generate a C source file that bakes pipeline JSON
// into the processor binary, so `dioramap-processor serve` works without
// --pipelines-dir. Invoked by core/CMakeLists.txt.
//
// Output schema (see core/include/v3/pipeline_embedded.h):
//   extern const embedded_pipeline_t v3_embedded_pipelines[];
//   extern const unsigned int        v3_embedded_pipelines_count;
//
// Usage: embed-pipelines.mjs --out <out.c> <pipeline.json>...
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';

const args = process.argv.slice(2);
let outPath = null;
const inputs = [];
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--out') outPath = args[++i];
  else inputs.push(args[i]);
}
if (!outPath || inputs.length === 0) {
  console.error('usage: embed-pipelines.mjs --out <out.c> <pipeline.json>...');
  process.exit(1);
}

const lines = [
  '// Generated by scripts/embed-pipelines.mjs — do not edit.',
  '',
  '#include <v3/pipeline_embedded.h>',
  '',
];
const entries = [];
for (const inp of inputs) {
  let json;
  try { json = JSON.parse(readFileSync(inp, 'utf8')); }
  catch (e) { console.error(`embed-pipelines: cannot read ${inp}: ${e.message}`); process.exit(1); }
  const id = `k_pipeline_${entries.length}`;
  const bytes = Buffer.from(JSON.stringify(json), 'utf8');
  lines.push(`// ${inp.split('/').slice(-2).join('/')} → "${json.name}"`);
  lines.push(`static const unsigned char ${id}[] = {`);
  for (let i = 0; i < bytes.length; i += 16) {
    const chunk = bytes.subarray(i, Math.min(i + 16, bytes.length));
    lines.push('    ' + Array.from(chunk).map(b => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
  }
  lines.push('};', '');
  entries.push({ id, name: json.name, len: bytes.length });
}
lines.push('const embedded_pipeline_t v3_embedded_pipelines[] = {');
for (const e of entries) {
  const cname = e.name.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  lines.push(`    { "${cname}", ${e.id}, ${e.len} },`);
}
lines.push('};', '', `const unsigned int v3_embedded_pipelines_count = ${entries.length};`, '');
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join('\n'));
